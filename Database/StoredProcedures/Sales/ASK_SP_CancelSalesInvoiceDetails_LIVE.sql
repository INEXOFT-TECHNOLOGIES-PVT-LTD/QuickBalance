CREATE PROCEDURE [dbo].[ASK_SP_CancelSalesInvoiceDetails]
	@SINVNO INT,
	@USERID INT
AS
BEGIN	
	SET NOCOUNT ON;
	BEGIN TRY
	BEGIN TRAN

	DECLARE @RESULT NVARCHAR(MAX) = ''

	DECLARE @SINVORDNO INT = 0, @GDNINVNO INT = 0, @GDNORDNO INT = 0, @YVRNO INT, @BANKYVRNO INT, @BANKYVRNOT INT, @CANCELFLG BIT
	SELECT @SINVORDNO = ORDNO, @GDNORDNO = GDNNO, @YVRNO = YVRNO, @BANKYVRNO = BANKYVRNO, @BANKYVRNOT = BANKYVRNOT, @CANCELFLG = CANCELFLG FROM SALM WHERE INVNO = @SINVNO AND STYPE = 'O'
	IF(@GDNORDNO <> 0)
		SELECT @GDNINVNO = INVNO FROM GDNM WHERE STYPE = 'DN' AND ORDNO = @GDNORDNO

	IF (ISNULL(@SINVORDNO, 0) = 0 OR ISNULL(@GDNORDNO, 0) = 0)
		SET @RESULT = 'The invoice could not be found. Therefore, the voucher cannot be cancelled.'
	ELSE IF (@CANCELFLG = 1)
		SET @RESULT = 'The invoice has already been cancelled.'
	ELSE IF EXISTS (SELECT SALM.INVNO FROM SALM INNER JOIN SALT ON SALM.INVNO = SALT.INVNO WHERE SALM.STYPE = 'R' AND SALM.RTNINVNO = @SINVORDNO AND SALM.CANCELFLG = 0 AND IIF(SALT.PRVR IS NULL, '', SALT.PRVR) <> 'Y')
		SET @RESULT = 'A return invoice already exists for this bill. The bill cannot be cancelled.'
	ELSE
	BEGIN

		--## Clear Stock
		UPDATE P SET P.STOCK = P.STOCK + D.QTY FROM PRMAST P INNER JOIN (SELECT PRCODE, SUM(CONVQTY) AS QTY FROM SALT WHERE INVNO = @SINVNO GROUP BY PRCODE) D on P.PRCODE = D.PRCODE

		--## Clear Batch Stock
		DECLARE @BATCHRTEDIT BIT
		SELECT @BATCHRTEDIT = BATCHRTEDIT FROM CONFIGTB
		UPDATE P  SET P.BALQTY = P.BALQTY + D.CONVQTY FROM PRST P 
		INNER JOIN (SELECT PRCODE, BATCH, GRACK, SUM(CONVQTY) AS CONVQTY, CONVMRP, CONVRATE, MFGDATE, EXPIRY FROM BATCHDET WHERE STYPE = 'O' AND VRNO = @SINVNO GROUP BY PRCODE, BATCH, GRACK, CONVMRP, CONVRATE, MFGDATE, EXPIRY) D ON P.PRCODE = D.PRCODE AND P.BATCH = D.BATCH AND P.GRACK = D.GRACK
		INNER JOIN PRMAST ON PRMAST.PRCODE = P.PRCODE WHERE ISNULL(D.BATCH, '') != '' AND (@BATCHRTEDIT = 1 OR (P.CONVRATE = D.CONVRATE AND P.CONVMRP = D.CONVMRP)) AND (PRMAST.MANDATEFLG = 0 OR P.MFGDATE = D.MFGDATE) AND (PRMAST.EXPDATEFLG = 0 OR P.EXPIRY = D.EXPIRY)

		--## Cancel Sales Invoice Details
		UPDATE SALM SET DISCP = 0, DISCVAL = 0, NTVALUE = 0, TVALUE = 0, TAX = 0, COINADJ = 0, AMOUNT = 0, FREIGHT = 0, ULOGCD = @USERID, UDATE = GETDATE(), CUSDUITY = 0, CURCONRATE = 0, CURCODE = 0, CANCELFLG = 1, BILLREFFLG = 0, PNTINID = 0, PNTINPER = 0, PNTINVAL = 0, PNTOUTID = 0, PNTOUTPER = 0, PNTOUTVAL = 0, CASHPAID = 0, BANKPAID = 0 WHERE INVNO = @SINVNO
		UPDATE SALT SET ORGRATE = RATE, ORGQTY = QTY, QTY = 0, RATE = 0, CANCELFLG = 1, CONVTYPE = -1, CONVFACT = 1, CONVQTY = 0,CONVRATE = 0 WHERE INVNO = @SINVNO
		UPDATE SALD SET ORGAMT = AMOUNT, ORGTAXAMT = TAXAMT, AMOUNT = 0, TAX = 0, TAXAMT = 0, CANCELFLG = 1 WHERE VRNO = @SINVNO

		DELETE FROM STKDT WHERE TRNNO = @SINVORDNO AND TYPE = 'I' AND VRTYPE = 'TR'
		DELETE FROM STKDTPHY WHERE TRNNO = @SINVORDNO AND TYPE = 'I' AND VRTYPE = 'TR'

		UPDATE YVR SET ORGREC = RECEIPT, ORGPAY = PAYMENT, RECEIPT = 0, PAYMENT = 0, CANCELFLG = 1 WHERE VRTYPE = 'RV' AND (VRNO IN (SELECT B.TYPECODE FROM BILLBYBILL B WHERE B.REFNO = @SINVORDNO AND B.VRTYPE = 'Sales' AND B.GENTYPE = 'S' ) OR VRNO IN (@YVRNO, @BANKYVRNO, @BANKYVRNOT))

		DELETE FROM BILLBYBILL WHERE REFNO = @SINVORDNO AND VRTYPE = 'Sales' AND GENTYPE = 'S'
		DELETE FROM BATCHDET WHERE VRNO = @SINVNO AND STYPE = 'O'

		UPDATE SNTSTK SET OUTVRTYPE = '', OUTVRNO = 0, OUTORDNO = 0, OUTSLNO = 0, USED = 0 WHERE OUTVRTYPE = 'SI' AND OUTVRNO = @SINVNO AND OUTORDNO = @SINVORDNO

		DELETE FROM SNTSTKPHY WHERE (INVRTYPE = 'SI' AND INVRNO = @SINVNO AND INORDNO = @SINVORDNO) OR (OUTVRTYPE = 'SI' AND OUTVRNO = @SINVNO AND OUTORDNO = @SINVORDNO)

		--## Cancel Goods Delivery Note Details
		UPDATE GDNM SET DISCP = 0, DISCVAL = 0, NTVALUE = 0, TVALUE = 0, TAX = 0, COINADJ = 0, AMOUNT = 0, FREIGHT = 0, CANCELFLG = 1, UDATE = GETDATE() WHERE INVNO = @GDNINVNO
		UPDATE GDNT SET ORGRATE = RATE, ORGQTY = QTY, QTY = 0, RATE = 0, CANCELFLG = 1, CONVTYPE = -1, CONVFACT = 1, CONVQTY = 0, CONVRATE = 0 WHERE INVNO = @GDNINVNO
		UPDATE GDND SET ORGAMT = AMOUNT, ORGTAXAMT = TAXAMT, CANCELFLG = 1, AMOUNT = 0, TAX = 0, TAXAMT = 0 WHERE VRNO = @GDNINVNO

		DELETE FROM STKDT WHERE NTNO = @GDNORDNO AND TYPE = 'I' AND VRTYPE = 'NT'
		DELETE FROM STKDTPHY WHERE NTNO = @GDNORDNO AND TYPE = 'I' AND VRTYPE = 'NT'

		DELETE FROM BATCHDET WHERE VRNO = @GDNINVNO AND STYPE = 'DN'

		--## Save LOGNOTE
		INSERT INTO [dbo].[LOGNOTE] (VRTYPE, VRNO, EDATE, USERCODE, NOTES, CFLAG, VSVRTYPE)
		SELECT 'S' AS VRTYPE, @SINVNO AS VRNO, GETDATE() AS EDATE, @USERID AS USERCODE, 'Cancel' AS NOTES, 0 AS CFLAG, 0 AS VSVRTYPE

		SET @RESULT = 'Cancelled'

	END

	SELECT @RESULT AS MESSAGE, (CASE WHEN @RESULT = 'Cancelled' THEN 1 ELSE 0 END) AS STATUS

	COMMIT TRAN
	END TRY
	BEGIN CATCH	
		IF(@@TRANCOUNT > 0)
			ROLLBACK TRAN;
	SELECT 'Error: ' + ERROR_MESSAGE() AS MESSAGE, 0 AS STATUS
	END CATCH
END



GO


