-- ==================================================
-- Author:		Ashique C (original draft, 02 Oct 2026)
-- Reviewed:	25 Nov 2026 - fixes marked "-- FIX n" (see list below)
-- Description:	Validate and Save/Update Sales Return Details
--
-- FIX 1  Saved/Updated and the GDNRVRNO counter reset were swapped (counter stayed -1 forever)
-- FIX 2  @SINVNO is the invoice INVNO (internal ID), same as the Sales Billing API
-- FIX 3  @SRETNO must be an existing, not-cancelled RETURN (STYPE 'R')
-- FIX 4  Original invoice: must exist, not cancelled, same customer
-- FIX 5  Max returnable qty: excludes cancelled returns, counts only already-converted rows
-- FIX 6  Batch check was inverted; now "batch must exist and match"; update check rewritten
-- FIX 7  BATCHDET uses STYPE = 'SR' (the draft used VSVRTYPE, which is always 0)
-- FIX 8  Serial: @SL table cleared per row; IN rows saved with USED = 0 and no cartesian join
-- FIX 9  Idempotency (same pattern as ASK_SP_ManageSalesInvoiceDetails)
-- FIX 10 Lock on the original invoice so two returns cannot both pass the qty check
-- FIX 11 Deletes limited to this voucher type (SALT STYPE 'R', SALD VRTYPE 'R')
-- FIX 12 SALD 'D' row: checks SRTNCODE (draft checked SALCODE but used SRTNCODE)
-- FIX 13 Result also returns INVNO, ORDNO, ISREPLAY; CATCH uses the billing error format
-- FIX 14 Date-block validation (as in billing); StartNo applied to new returns only
-- ==================================================
CREATE PROCEDURE [dbo].[ASK_SP_ManageSalesReturnDetails]
	@SRETNO INT,			-- 0 = new return, otherwise the return's INVNO
	@SINVNO INT,			-- FIX 2: original sales invoice INVNO, 0 = return without invoice
	@DATE DATETIME,
	@CUSCODE INT,
	@PAYMODE NVARCHAR(100),
	@CLCODE INT,
	@BLCODE INT,
	@DUEDATE DATETIME,
	@SMCODE INT,
	@DISCPERC DECIMAL(18, 6),
	@DISCAMT DECIMAL(18, 6),
	@ROUNDOFF DECIMAL(18, 6),
	@USERID INT,
	@IDEMPOTENCYKEY NVARCHAR(100),	-- FIX 9
	@REQUESTHASH CHAR(64),			-- FIX 9
	@ITEMDTLS AS ASK_UDT_SalesReturnItem READONLY,
	@SLNODTLS AS ASK_UDT_SalesReturnSerialNumber READONLY,
	@ADDIDTLS AS ASK_UDT_SalesReturnAdditionalInfo READONLY
AS
BEGIN
	SET NOCOUNT ON;
	BEGIN TRY
	BEGIN TRANSACTION;

	IF OBJECT_ID('tempdb..#TEMP_SR') IS NOT NULL
		DROP TABLE #TEMP_SR

	DECLARE @RESULT NVARCHAR(MAX) = ''
	DECLARE @INVNO INT = 0, @ORDNO INT = 0
	DECLARE @LOCKRESULT INT

	--## Existing return (update)  -- FIX 3
	DECLARE @SRETORDNO INT = 0, @SRETCANCEL INT = 0
	IF(@SRETNO <> 0)
		SELECT @SRETORDNO = ORDNO, @SRETCANCEL = ISNULL(CANCELFLG, 0) FROM SALM WHERE INVNO = @SRETNO AND STYPE = 'R'

	--## Original sales invoice  -- FIX 2, FIX 4
	DECLARE @SINVORDNO INT = 0, @SINVCUSCODE INT = 0, @SINVCANCEL INT = 0, @SINVTEXT NVARCHAR(MAX) = ''
	IF(@SINVNO <> 0)
		SELECT @SINVORDNO = ORDNO, @SINVCUSCODE = CUSTCODE, @SINVCANCEL = ISNULL(CANCELFLG, 0), @SINVTEXT = ISNULL(INVNOTEXT, '') FROM SALM WHERE INVNO = @SINVNO AND STYPE = 'O'

	--## Variable Declaration
	DECLARE @ALTUNITWISE BIT, @DATEBLOCK BIT, @SUDATEBLOCK INT, @TAGACCMSTR INT, @COSTC BIT, @BATCHWISE BIT, @BATCHRTEDIT BIT, @SLNOWISE BIT, @MULTIALIAS BIT, @SRWITHOUTINV BIT
	SELECT @ALTUNITWISE = ALTUNIT, @DATEBLOCK = DATEBLOCK, @SUDATEBLOCK = SUDATEBLOCK, @TAGACCMSTR = TAGACCMSTR, @COSTC = COSTC, @BATCHWISE = BATCHWISE, @BATCHRTEDIT = BATCHRTEDIT, @SLNOWISE = SLNOTRACK, @MULTIALIAS = MULTIALIAS, @SRWITHOUTINV = SRWITHOUTINV FROM CONFIGTB

	DECLARE @CASHCD INT, @DISCCD INT, @COINADJCD INT
	SELECT @CASHCD = CASHCD, @DISCCD = DISCCD, @COINADJCD = COINADJCD FROM FYDETAILS WHERE PREVFIN = 0
	SET @CLCODE = CASE WHEN @PAYMODE = 'Cash' AND @CLCODE = 0 THEN @CASHCD ELSE @CLCODE END

	DECLARE @USERTYPE NVARCHAR(MAX) = (SELECT USERTYPE FROM TBUSER WHERE USERCODE = @USERID)
	DECLARE @SLNOINSERT TABLE (PRCODE INT, INSLNO INT, GDWCODE INT, UNITCODE INT, ITEMSLNO NVARCHAR(MAX))

	DECLARE @BTYPE NVARCHAR(1) = CASE WHEN @PAYMODE = 'Cash' THEN 'C' WHEN @PAYMODE = 'Credit' THEN 'R' ELSE 'B' END
	DECLARE @ADJCD INT = (CASE WHEN @PAYMODE = 'Cash' THEN @CLCODE WHEN @PAYMODE = 'Bank' THEN @BLCODE ELSE 0 END)

	SELECT H.SLNO, H.PRCODE, P.PRNAME, GDWCODE, H.UNITCODE, P.UNIT AS MAINUNIT, P.ALTUNIT AS ALTUNIT, H.ALCODE, H.ALNAME,

	H.QTY, H.QTY AS CONVQTY,
	H.RATE, H.RATE AS CONVRATE,

	ISNULL(H.PRRATE, CAST(0 AS DECIMAL(18,6))) AS PRRATE, ISNULL(H.PRRATE, CAST(0 AS DECIMAL(18,6))) AS CONVPRRATE,
	ISNULL(H.MRP, CAST(0 AS DECIMAL(18,6))) AS MRP, ISNULL(H.MRP, CAST(0 AS DECIMAL(18,6))) AS CONVMRP,

	ISNULL(H.LDISCPERC, CAST(0 AS DECIMAL(18,6))) AS LDISCPERC, ISNULL(H.LDISCPRICE, CAST(0 AS DECIMAL(18,6))) AS LDISCPRICE,
	ISNULL(H.DISCPERC, CAST(0 AS DECIMAL(18,6))) AS DISCPERC, ISNULL(H.DISCPRICE, CAST(0 AS DECIMAL(18,6))) AS DISCPRICE,

	ISNULL(H.BATCH, '') AS BATCH, ISNULL(H.MFGDATE, @DATE) AS MFGDATE, ISNULL(H.EXPDATE, @DATE) AS EXPDATE,
	P.BASEMINPRICE, P.ALTSALEPRICE, ISNULL(H.TAXABLE,CAST(0 AS DECIMAL(18,6))) AS TAXABLE, H.TAXCODE, ISNULL(H.TAXPERC,CAST(0 AS DECIMAL(18,6))) AS TAXPERC, ISNULL(H.TAXAMOUNT,CAST(0 AS DECIMAL(18,6))) AS TAXAMOUNT, ISNULL(H.NETAMOUNT,CAST(0 AS DECIMAL(18,6))) AS NETAMOUNT,
	CASE WHEN @ALTUNITWISE = 1 AND P.ALTUNIT > 0 AND P.SALESPRICETYPE = 1 THEN 1 ELSE 0 END AS PRFLG, (CASE WHEN @SRETNO <> 0 THEN H.CONVTYPE ELSE P.CONVTYPE END) AS CONVTYPE, (CASE WHEN @SRETNO <> 0 THEN H.CONVFACT ELSE P.UNITCONV END) AS CONVFACT,
	P.SERVFLG, P.BATCHFLG, P.SLNOTRACK INTO #TEMP_SR FROM @ITEMDTLS H INNER JOIN PRMAST P ON H.PRCODE = P.PRCODE

	--## Header validation
	IF (@SRETNO <> 0 AND @SRETORDNO = 0)
		SET @RESULT = 'Sales return not found.'																	-- FIX 3
	ELSE IF (@SRETNO <> 0 AND @SRETCANCEL = 1)
		SET @RESULT = 'Cancelled sales returns cannot be edited.'												-- FIX 3
	ELSE IF (SELECT COUNT(*) FROM #TEMP_SR) = 0
		SET @RESULT = 'Item Details Must not be blank'
	ELSE IF EXISTS (SELECT * FROM CUSMAS WHERE ACCID = @CUSCODE AND COUNTRYCODE <> 0 AND COUNTRYCODE <> (SELECT TOP 1 COUNTRY FROM COMPMAS))
		SET @RESULT = 'Sales return creation is restricted. Outside parties are not allowed.'
	ELSE IF (@SINVNO = 0 AND ISNULL(@SRWITHOUTINV, 0) = 0)
		SET @RESULT = 'Please ensure a sales invoice bill number exists before creating a return.'
	ELSE IF (@SINVNO <> 0 AND @SINVORDNO = 0)
		SET @RESULT = 'Sales invoice not found.'																-- FIX 4
	ELSE IF (@SINVNO <> 0 AND @SINVCANCEL = 1)
		SET @RESULT = 'This Bill is Cancelled'																	-- FIX 4
	ELSE IF (@SINVNO <> 0 AND @SINVCUSCODE <> @CUSCODE)
		SET @RESULT = 'The selected sales invoice belongs to a different customer.'								-- FIX 4
	ELSE IF (@SRETNO = 0 AND @DATEBLOCK = 1 AND (@USERTYPE <> 'SuperUser' OR @SUDATEBLOCK = 1)
			AND @DATE < ISNULL((SELECT MAX(INVDATE) FROM SALM WHERE STYPE = 'R'), @DATE))						-- FIX 14
		SET @RESULT = CASE WHEN @USERTYPE <> 'SuperUser' THEN 'Backdated Entries Not Allowed On This User. Please Contact Your Super To User.' ELSE 'Selected Date Is Less Than Last Voucher Date' END

	-- ============================================
	-- IDEMPOTENCY CHECK  -- FIX 9 (same as billing, own lock prefix)
	-- ============================================
	IF @SRETNO = 0
	BEGIN
		IF NULLIF(LTRIM(RTRIM(@IDEMPOTENCYKEY)), N'') IS NULL
			THROW 50001, 'Idempotency-Key is required.', 1;

		IF @REQUESTHASH IS NULL
			THROW 50002, 'Request hash is required.', 1;

		DECLARE @LOCKRESOURCE NVARCHAR(255) = N'SalesReturn:' + CONVERT(NVARCHAR(20), @USERID) + N':' + @IDEMPOTENCYKEY;

		EXEC @LOCKRESULT = sys.sp_getapplock
			@Resource = @LOCKRESOURCE,
			@LockMode = 'Exclusive',
			@LockOwner = 'Transaction',
			@LockTimeout = 10000;

		IF @LOCKRESULT < 0
			THROW 50003, 'Unable to acquire sales return request lock.', 1;

		IF EXISTS (SELECT 1 FROM dbo.API_IDEMPOTENCY WHERE USERID = @USERID AND IDEMPOTENCYKEY = @IDEMPOTENCYKEY)
		BEGIN
			IF EXISTS (SELECT 1 FROM dbo.API_IDEMPOTENCY WHERE USERID = @USERID AND IDEMPOTENCYKEY = @IDEMPOTENCYKEY AND REQUESTHASH <> @REQUESTHASH)
				THROW 50004, 'Idempotency-Key was used with different request data.', 1;

			SELECT MESSAGE, STATUS, INVNO, ORDNO, CAST(1 AS BIT) AS ISREPLAY
			FROM dbo.API_IDEMPOTENCY
			WHERE USERID = @USERID AND IDEMPOTENCYKEY = @IDEMPOTENCYKEY;

			COMMIT TRANSACTION;
			RETURN;
		END
	END

	--## Lock the original invoice  -- FIX 10
	--   Two returns against the same invoice saved at the same moment would both pass the
	--   max-qty check. This lock makes the second one wait until the first is committed.
	IF (@RESULT = '' AND @SINVNO <> 0)
	BEGIN
		DECLARE @INVLOCK NVARCHAR(255) = N'SalesReturnInvoice:' + CONVERT(NVARCHAR(20), @SINVNO);

		EXEC @LOCKRESULT = sys.sp_getapplock
			@Resource = @INVLOCK,
			@LockMode = 'Exclusive',
			@LockOwner = 'Transaction',
			@LockTimeout = 10000;

		IF @LOCKRESULT < 0
			THROW 50003, 'Another return for this sales invoice is being saved. Please retry.', 1;
	END

	--## Line validation
	IF(@RESULT = '')
	BEGIN
		DECLARE @ROWNO INT = 1
		DECLARE @MinSLNO INT = (SELECT MIN(SLNO) FROM #TEMP_SR)
		DECLARE @MaxSLNO INT = (SELECT MAX(SLNO) FROM #TEMP_SR)
		DECLARE @SL TABLE (SLNO INT IDENTITY(1,1), ITEMSLNO NVARCHAR(MAX))		-- FIX 8: declared once, cleared per row

		WHILE (@MinSLNO <= @MaxSLNO)
		BEGIN

			IF (@RESULT <> '') BREAK

			DECLARE @PRCODE INT, @PRNAME NVARCHAR(MAX), @BATCHFLG BIT, @BATCH NVARCHAR(MAX), @MFGDATE DATETIME, @EXPDATE DATETIME, @SLNOTRACK BIT, @GDWCODE INT, @UNITCODE INT, @MAINUNIT INT, @ALTUNIT INT, @QTY DECIMAL(18, 6), @ALCODE NVARCHAR(MAX), @ALNAME NVARCHAR(MAX), @RATE DECIMAL(18, 6), @PRRATE DECIMAL(18, 6), @MRP DECIMAL(18, 6), @CONVTYPE INT, @CONVFACT DECIMAL(18, 6)
			SELECT @PRCODE = PRCODE, @PRNAME = PRNAME, @BATCHFLG = BATCHFLG, @BATCH = BATCH, @MFGDATE = MFGDATE, @EXPDATE = EXPDATE, @SLNOTRACK = SLNOTRACK, @GDWCODE = GDWCODE, @UNITCODE = UNITCODE, @MAINUNIT = MAINUNIT, @ALTUNIT = ALTUNIT, @QTY = QTY, @ALCODE = ALCODE, @ALNAME = ALNAME, @RATE = RATE, @PRRATE = PRRATE, @MRP = MRP, @CONVTYPE = CONVTYPE, @CONVFACT = CONVFACT FROM #TEMP_SR WHERE SLNO = @MinSLNO

			--## Get Alias Quantity
			DECLARE @ALQTY DECIMAL(18, 6) = 0
			SELECT @ALQTY = ISNULL(MAX(A.QTY),0), @ALNAME = ISNULL(MAX(A.ALNAME),@ALNAME) FROM PRMAST P INNER JOIN PRALIAS A ON P.PRCODE = A.PRCODE WHERE P.PRCODE = @PRCODE AND (CAST(A.CODE AS nvarchar(MAX)) = @ALCODE OR A.ALNAME = @ALNAME)

			--## Convert to main unit
			DECLARE @CONVQTY DECIMAL(18, 6) = @QTY, @CONVRATE DECIMAL(18, 6) = @RATE, @CONVPRRATE DECIMAL(18, 6) = @PRRATE, @CONVMRP DECIMAL(18, 6) = @MRP
			SET @CONVQTY = (CASE WHEN @MULTIALIAS = 1 AND ISNULL(@ALCODE,'') <> '' AND @ALQTY <> 0 THEN @ALQTY ELSE CAST(1 AS DECIMAL(18, 6)) END) * (CASE WHEN @UNITCODE = @MAINUNIT THEN @CONVQTY WHEN @CONVTYPE = 0 AND @CONVFACT <> 0 THEN @CONVQTY*@CONVFACT WHEN @CONVTYPE = 1 AND @CONVFACT <> 0 THEN @CONVQTY/@CONVFACT ELSE @CONVQTY END)
			SET @CONVRATE = (CASE WHEN @UNITCODE = @MAINUNIT THEN @CONVRATE WHEN @CONVTYPE = 0 AND @CONVFACT <> 0 THEN @CONVRATE/@CONVFACT WHEN @CONVTYPE = 1 AND @CONVFACT <> 0 THEN @CONVRATE*@CONVFACT ELSE @CONVRATE END) / (CASE WHEN @MULTIALIAS = 1 AND ISNULL(@ALCODE,'') <> '' AND @ALQTY <> 0 THEN @ALQTY ELSE CAST(1 AS DECIMAL(18, 6)) END)
			SET @CONVPRRATE = (CASE WHEN @UNITCODE = @MAINUNIT THEN @CONVPRRATE WHEN @CONVTYPE = 0 AND @CONVFACT <> 0 THEN @CONVPRRATE/@CONVFACT WHEN @CONVTYPE = 1 AND @CONVFACT <> 0 THEN @CONVPRRATE*@CONVFACT ELSE @CONVPRRATE END)
			SET @CONVMRP = (CASE WHEN @UNITCODE = @MAINUNIT THEN @CONVMRP WHEN @CONVTYPE = 0 AND @CONVFACT <> 0 THEN @CONVMRP/@CONVFACT WHEN @CONVTYPE = 1 AND @CONVFACT <> 0 THEN @CONVMRP*@CONVFACT ELSE @CONVMRP END)

			--## Update #TEMP_SR
			UPDATE #TEMP_SR SET ALNAME = @ALNAME, CONVQTY = @CONVQTY, CONVRATE = @CONVRATE, CONVPRRATE = @CONVPRRATE, CONVMRP = @CONVMRP WHERE SLNO = @MinSLNO

			--## Max returnable quantity  -- FIX 5
			--   sold on the invoice - already returned by OTHER, NOT-cancelled returns >= entered so far
			--   "SLNO <= @MinSLNO" = only rows already converted to main unit; the last row of a
			--   product therefore checks the full total of that product.
			IF(@SINVNO <> 0)
			BEGIN
				DECLARE @SOLDQTY DECIMAL(18, 6) = (SELECT ISNULL(SUM(CONVQTY), 0) FROM SALT WHERE STYPE = 'O' AND INVNO = @SINVNO AND PRCODE = @PRCODE)
				DECLARE @RETURNEDQTY DECIMAL(18, 6) = (SELECT ISNULL(SUM(T.CONVQTY), 0) FROM SALT T WHERE T.STYPE = 'R' AND T.RTNINVNO = @SINVORDNO AND T.PRCODE = @PRCODE AND T.INVNO <> @SRETNO
														AND NOT EXISTS (SELECT 1 FROM SALM M WHERE M.INVNO = T.INVNO AND ISNULL(M.CANCELFLG, 0) = 1))
				DECLARE @ENTERQTY DECIMAL(18, 6) = (SELECT ISNULL(SUM(CONVQTY), 0) FROM #TEMP_SR WHERE PRCODE = @PRCODE AND SLNO <= @MinSLNO)

				IF (@SOLDQTY = 0)
					SET @RESULT = 'Product '''+@PRNAME+''' at Row: '+CAST(@ROWNO AS NVARCHAR)+' is not in sales invoice '''+@SINVTEXT+'''.'
				ELSE IF (@RETURNEDQTY + @ENTERQTY > @SOLDQTY)
					SET @RESULT = 'Return quantity is more than the quantity still returnable for product: '''+@PRNAME+''' at Row: '+CAST(@ROWNO AS NVARCHAR)+' (sold: '+FORMAT(@SOLDQTY, 'N2')+', already returned: '+FORMAT(@RETURNEDQTY, 'N2')+').'
			END

			--## Batch Validation  -- FIX 6
			--   A returned batch must already exist in this godown and match its rate/MRP/dates
			--   (unless BATCHRTEDIT). Same comparison style as the billing procedure.
			IF(@RESULT = '' AND @BATCHWISE = 1 AND @BATCHFLG = 1)
			BEGIN
				IF(@BATCH = '')
					SET @RESULT = 'Missing batch details Product: '+@PRNAME+' at Row: '+CAST(@ROWNO AS NVARCHAR)
				ELSE IF NOT EXISTS (SELECT 1 FROM PRST BT WHERE BT.PRCODE = @PRCODE AND BT.GRACK = @GDWCODE AND BT.BATCH = @BATCH)
					SET @RESULT = 'Batch '''+@BATCH+''' was not found in the selected godown for product: '''+@PRNAME+''' at Row: '+CAST(@ROWNO AS NVARCHAR)
				ELSE IF NOT EXISTS (SELECT 1 FROM PRST BT INNER JOIN PRMAST PR ON BT.PRCODE = PR.PRCODE
									WHERE BT.PRCODE = @PRCODE AND BT.GRACK = @GDWCODE AND BT.BATCH = @BATCH
									AND (@BATCHRTEDIT = 1 OR (BT.CONVRATE = @CONVMRP AND BT.CONVMRP = @CONVRATE))
									AND (ISNULL(PR.MANDATEFLG, 0) = 0 OR BT.MFGDATE = @MFGDATE)
									AND (ISNULL(PR.EXPDATEFLG, 0) = 0 OR BT.EXPIRY = @EXPDATE))
					SET @RESULT = 'Batch details (rate, MRP, expiry or manufacturing date) do not match batch '''+@BATCH+''' for product: '''+@PRNAME+''' at Row: '+CAST(@ROWNO AS NVARCHAR)
			END

			--## Serial Number Tracking Validation
			IF(@RESULT = '' AND @SLNOWISE = 1 AND @SLNOTRACK = 1)
			BEGIN
				DECLARE @SLNO_COUNT INT = (SELECT COUNT(*) FROM @SLNODTLS WHERE PRCODE = @PRCODE AND INSLNO = @MinSLNO)
				DECLARE @DUPLICATE_SLNO NVARCHAR(100) = NULL
				SELECT TOP 1 @DUPLICATE_SLNO = ITEMSLNO FROM @SLNODTLS WHERE PRCODE = @PRCODE GROUP BY ITEMSLNO HAVING COUNT(ITEMSLNO) > 1

				IF (@SLNO_COUNT = 0)
					SET @RESULT = 'Missing serial number tracking details for product: '''+@PRNAME+''' at Row: '+CAST(@ROWNO AS NVARCHAR)
				ELSE IF (@QTY % 1 <> 0)
					SET @RESULT = 'Decimal numbers are not allowed with serial number tracking for Product: '''+@PRNAME+''' at Row: '+CAST(@ROWNO AS NVARCHAR)
				ELSE IF (@SLNO_COUNT > @QTY)
					SET @RESULT = 'Entered quantity is greater than serial number tracking record for product: '''+@PRNAME+''' at Row: '+CAST(@ROWNO AS NVARCHAR)
				ELSE IF (@SLNO_COUNT < @QTY)
					SET @RESULT = 'Entered quantity is less than serial number tracking record for product: '''+@PRNAME+''' at Row: '+CAST(@ROWNO AS NVARCHAR)
				ELSE IF @DUPLICATE_SLNO IS NOT NULL
					SET @RESULT = 'Serial number '''+@DUPLICATE_SLNO+''' is duplicated for product: '''+@PRNAME+''' at Row: '+CAST(@ROWNO AS NVARCHAR)
				ELSE
				BEGIN
					DELETE FROM @SL																					-- FIX 8
					INSERT INTO @SL (ITEMSLNO) SELECT ITEMSLNO FROM @SLNODTLS WHERE PRCODE = @PRCODE AND INSLNO = @MinSLNO

					DECLARE @MinINSLNO INT = (SELECT MIN(SLNO) FROM @SL)											-- FIX 8 (IDENTITY keeps counting after DELETE)
					DECLARE @MaxINSLNO INT = (SELECT MAX(SLNO) FROM @SL)

					WHILE (@MinINSLNO <= @MaxINSLNO)
					BEGIN

						IF (@RESULT <> '') BREAK

						DECLARE @ITEMSLNO NVARCHAR(MAX) = (SELECT ITEMSLNO FROM @SL WHERE SLNO = @MinINSLNO)
						DECLARE @USED INT = (SELECT COUNT(*) FROM SNTSTK S WHERE S.ITEMSLNO = @ITEMSLNO AND S.PRCODE = @PRCODE AND S.GDWCODE = @GDWCODE AND S.UNITCODE = @UNITCODE AND ISNULL(S.USED, 0) = 0 AND (S.INVRTYPE <> 'SR' OR S.INVRNO <> @SRETNO))

						IF(@USED > 0)
							SET @RESULT = 'Serial number '''+@ITEMSLNO+''' is already in stock for product: '''+@PRNAME+''' at Row: '+CAST(@ROWNO AS NVARCHAR)
						ELSE IF @SINVNO <> 0 AND NOT EXISTS (SELECT * FROM SNTSTK WHERE OUTVRTYPE = 'SI' AND OUTORDNO = @SINVORDNO AND OUTVRNO = @SINVNO AND PRCODE = @PRCODE AND GDWCODE = @GDWCODE AND UNITCODE = @UNITCODE AND ITEMSLNO = @ITEMSLNO)
							SET @RESULT = 'Serial number '''+@ITEMSLNO+''' in Sales Return does not match the Sales record for selected '''+@PRNAME+''' product at Row: '+CAST(@ROWNO AS NVARCHAR)
						ELSE
							INSERT INTO @SLNOINSERT (PRCODE, INSLNO, GDWCODE, UNITCODE, ITEMSLNO) VALUES (@PRCODE, @MinSLNO, @GDWCODE, @UNITCODE, @ITEMSLNO)

						SET @MinINSLNO = @MinINSLNO + 1
					END
				END
			END

			SET @MinSLNO = CASE WHEN @RESULT <> '' OR NOT EXISTS (SELECT * FROM #TEMP_SR WHERE SLNO > @MinSLNO) THEN (@MaxSLNO + 1) ELSE (SELECT MIN(SLNO) FROM #TEMP_SR WHERE SLNO > @MinSLNO) END
			SET @ROWNO = @ROWNO + 1
		END
	END

	--## Update only: batch stock must not go negative  -- FIX 6
	--   new batch balance = current BALQTY - old qty of this return + new qty of this return
	IF(@RESULT = '' AND @BATCHWISE = 1 AND @SRETNO <> 0)
	BEGIN
		SELECT TOP 1 @RESULT = 'Batch Stock Will Go To Negative for product: '''+PR.PRNAME+''' batch: '''+X.BATCH+''''
		FROM (SELECT PRCODE, BATCH, GDWCODE, SUM(QTY) AS QTY FROM (
				SELECT PRCODE, BATCH, GRACK AS GDWCODE, -1 * CONVQTY AS QTY FROM BATCHDET WHERE STYPE = 'SR' AND VRNO = @SRETNO
				UNION ALL
				SELECT PRCODE, BATCH, GDWCODE, CONVQTY AS QTY FROM #TEMP_SR WHERE BATCH <> '') A
			  GROUP BY PRCODE, BATCH, GDWCODE) X
		INNER JOIN PRMAST PR ON PR.PRCODE = X.PRCODE
		INNER JOIN (SELECT PRCODE, BATCH, GRACK, SUM(BALQTY) AS BALQTY FROM PRST GROUP BY PRCODE, BATCH, GRACK) BT
			ON BT.PRCODE = X.PRCODE AND BT.BATCH = X.BATCH AND BT.GRACK = X.GDWCODE
		WHERE PR.BATCHFLG = 1 AND BT.BALQTY + X.QTY < 0
	END

	--## Update only: a returned serial that was sold again must stay in the return
	IF(@RESULT = '' AND @SLNOWISE = 1 AND @SRETNO <> 0)
	BEGIN
		DECLARE @PRNAME_MISS NVARCHAR(MAX), @SLNO_MISS NVARCHAR(MAX)

		SELECT TOP 1 @PRNAME_MISS = PT.PRNAME, @SLNO_MISS = UD.ITEMSLNO FROM (SELECT * FROM SNTSTK WHERE INVRTYPE = 'SR' AND INORDNO = @SRETORDNO AND INVRNO = @SRETNO AND USED = 1) AS UD
		INNER JOIN PRMAST AS PT ON UD.PRCODE = PT.PRCODE
		LEFT JOIN @SLNODTLS AS ER ON UD.PRCODE = ER.PRCODE AND UD.ITEMSLNO = ER.ITEMSLNO WHERE PT.SLNOTRACK = 1 AND ER.PRCODE IS NULL

		IF (ISNULL(@PRNAME_MISS, '') <> '')
			SET @RESULT = 'The serial number ''' + @SLNO_MISS + ''' has already been used for the product ''' + @PRNAME_MISS + ''' and is missing.'
	END

	IF (@RESULT = '' AND @SRETNO = 0 AND (SELECT TOP 1 GDNRVRNO FROM FYDETAILS) = -1)
		SET @RESULT = 'Something went wrong. Please try again.'

	IF (@RESULT = '')
	BEGIN

		IF(@SRETNO <> 0)
		BEGIN
			SET @INVNO = @SRETNO
			SET @ORDNO = @SRETORDNO
		END
		ELSE
		BEGIN
			UPDATE FYDETAILS SET @ORDNO = GDNRVRNO, GDNRVRNO = -1

			SET @ORDNO = @ORDNO + 1
			IF EXISTS(SELECT * FROM SALM WHERE STYPE = 'R' AND ORDNO = @ORDNO)
				SET @ORDNO = (SELECT MAX(ORDNO) + 1 FROM SALM WHERE STYPE = 'R')
		END

		--## Generate INVNOTEXT
		DECLARE @EmbDate NVARCHAR(MAX), @Emp NVARCHAR(MAX), @FYStatus INT, @FYDateFrom DATETIME, @FYDateTo DATETIME
		DECLARE @Prefit NVARCHAR(MAX), @Seperator NVARCHAR(MAX), @Suffix NVARCHAR(MAX), @fixedLength NVARCHAR(MAX), @Length INT, @StartNo int
		SELECT @FYStatus = CASE WHEN YEAR(FYDATEFR) = YEAR(FYDATETO) THEN 1 ELSE 0 END, @FYDateFrom = FYDATEFR, @FYDateTo = FYDATETO FROM FYDETAILS

		SELECT @EmbDate = EMBDATE, @Emp = CASE WHEN ISNULL(EMBDATE,'') = '' OR ISNULL(EMBFORMAT,'') = '' THEN '' ELSE (CASE WHEN @FYStatus = 1 THEN FORMAT(@FYDateFrom,'yyyy') WHEN EMBFORMAT = 'YYYY-YY' THEN FORMAT(@FYDateFrom,'yyyy')+'-'+FORMAT(@FYDateTo,'yy') ELSE FORMAT(@FYDateFrom,'yy')+'-'+FORMAT(@FYDateTo,'yy') END) END,
		@Prefit = ISNULL(PREFIX,''), @Seperator = ISNULL(SEPERATOR,''), @Suffix = ISNULL(SUFFIX,''), @fixedLength = ISNULL(FIXLENGTH,''), @Length = CAST(ISNULL([LENGTH],0) AS INT), @StartNo = CAST(ISNULL(STARTNO,0) AS INT) FROM VRNOCONF WHERE VRTYPE = 'Sales Return'
		SET @ORDNO = CASE WHEN @SRETNO = 0 AND @ORDNO = 1 AND @StartNo > 0 THEN @StartNo ELSE @ORDNO END		-- FIX 14
