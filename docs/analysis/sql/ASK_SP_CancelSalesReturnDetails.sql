CREATE PROCEDURE [dbo].[ASK_SP_CancelSalesReturnDetails]
	@SRETNO INT,
	@USERID INT
AS
BEGIN	
	SET NOCOUNT ON;
	BEGIN TRY
	BEGIN TRAN

	DECLARE @RESULT NVARCHAR(MAX) = ''

	DECLARE @SRETORDNO INT = 0, @YVRNO INT, @CANCELFLG BIT
	SELECT @SRETORDNO = ORDNO, @YVRNO = YVRNO, @CANCELFLG = CANCELFLG FROM SALM WHERE INVNO = @SRETNO AND STYPE = 'R'

	DECLARE @BATCHRTEDIT BIT
	SELECT @BATCHRTEDIT = BATCHRTEDIT FROM CONFIGTB

	IF (ISNULL(@SRETORDNO, 0) = 0)
		SET @RESULT = 'The return voucher could not be found. Therefore, the voucher cannot be cancelled.'
	ELSE IF (@CANCELFLG = 1)
		SET @RESULT = 'The return voucher has already been cancelled.'
	ELSE IF EXISTS (SELECT PR.PRNAME FROM (SELECT PRCODE, BATCH, CONVMRP, CONVRATE, MFGDATE, EXPIRY, SUM(CONVQTY) AS QTY FROM BATCHDET WHERE STYPE = 'SR' AND VRNO = @SRETNO GROUP BY PRCODE, BATCH, CONVMRP, CONVRATE, MFGDATE, EXPIRY) AS SR
		INNER JOIN PRMAST PR ON SR.PRCODE = PR.PRCODE
		INNER JOIN PRST BT ON SR.PRCODE = BT.PRCODE AND SR.BATCH = BT.BATCH
		WHERE (@BATCHRTEDIT = 1 OR (SR.CONVRATE = BT.CONVRATE AND SR.CONVMRP = BT.CONVMRP)) AND (PR.MANDATEFLG = 0 OR SR.MFGDATE = BT.MFGDATE) AND (PR.EXPDATEFLG = 0 OR SR.EXPIRY = BT.EXPIRY) AND PR.BATCHFLG = 1 AND SR.QTY < BT.BALQTY)
		SET @RESULT = 'Batch Stock Will Go To Negative. Can''t Cancel This Sales Return.'
	ELSE IF EXISTS (SELECT * FROM SNTSTK WHERE INVRTYPE = 'SR' AND INORDNO = @SRETORDNO AND INVRNO = @SRETNO AND USED = 1)
	BEGIN
		SET @RESULT = 'Serial number tracking details is already used. Can''t Cancel This Bill'
	END
	ELSE
	BEGIN

		--## Clear Stock
		UPDATE P SET P.STOCK = P.STOCK - D.QTY FROM PRMAST P INNER JOIN (SELECT PRCODE, SUM(CONVQTY) AS QTY FROM SALT WHERE INVNO = @SRETNO GROUP BY PRCODE) D on P.PRCODE = D.PRCODE

		--## Clear Batch Stock
		UPDATE P  SET P.BALQTY = P.BALQTY - D.CONVQTY FROM PRST P 
		INNER JOIN (SELECT PRCODE, BATCH, GRACK, SUM(CONVQTY) AS CONVQTY, CONVMRP, CONVRATE, MFGDATE, EXPIRY FROM BATCHDET WHERE STYPE = 'SR' AND VRNO = @SRETNO GROUP BY PRCODE, BATCH, GRACK, CONVMRP, CONVRATE, MFGDATE, EXPIRY) D ON P.PRCODE = D.PRCODE AND P.BATCH = D.BATCH AND P.GRACK = D.GRACK
		INNER JOIN PRMAST ON PRMAST.PRCODE = P.PRCODE WHERE ISNULL(D.BATCH, '') != '' AND (@BATCHRTEDIT = 1 OR (P.CONVRATE = D.CONVRATE AND P.CONVMRP = D.CONVMRP)) AND (PRMAST.MANDATEFLG = 0 OR P.MFGDATE = D.MFGDATE) AND (PRMAST.EXPDATEFLG = 0 OR P.EXPIRY = D.EXPIRY)

		--## Cancel Sales Return Details
		UPDATE SALM SET DISCP = 0, DISCVAL = 0, NTVALUE = 0, TVALUE = 0, TAX = 0, COINADJ = 0, AMOUNT = 0, FREIGHT = 0, ULOGCD = @USERID, UDATE = GETDATE(), CUSDUITY = 0, CURCONRATE = 0, CURCODE = 0, CANCELFLG = 1, BILLREFFLG = 0, PNTINID = 0, PNTINPER = 0, PNTINVAL = 0, PNTOUTID = 0, PNTOUTPER = 0, PNTOUTVAL = 0, CASHPAID = 0, BANKPAID = 0 WHERE INVNO = @SRETNO
		UPDATE SALT SET ORGRATE = RATE, ORGQTY = QTY, QTY = 0, RATE = 0, CANCELFLG = 1, CONVTYPE = -1, CONVFACT = 1, CONVQTY = 0,CONVRATE = 0 WHERE INVNO = @SRETNO
		UPDATE SALD SET ORGAMT = AMOUNT, ORGTAXAMT = TAXAMT, AMOUNT = 0, TAX = 0, TAXAMT = 0, CANCELFLG = 1 WHERE VRNO = @SRETNO

		DELETE FROM STKDT WHERE TRNNO = @SRETNO AND TYPE = 'R' AND VRTYPE = 'RET'
		DELETE FROM STKDTPHY WHERE TRNNO = @SRETNO AND TYPE = 'R' AND VRTYPE = 'RET'

		UPDATE YVR SET ORGREC = RECEIPT, ORGPAY = PAYMENT, RECEIPT = 0, PAYMENT = 0, CANCELFLG = 1 WHERE VRTYPE = 'PV' AND VRNO = @YVRNO
		UPDATE SALM SET BILLREFFLG = 0 WHERE STYPE = 'O' AND CAST(ORDNO AS NVARCHAR(100)) IN (SELECT REFNO FROM BILLBYBILL WHERE TYPECODE = @SRETORDNO AND STYPE = 'SalesReturn' AND METHOD = 'Adjustment' AND VRTYPE = 'Sales' AND REFNO <> '')
		UPDATE PENDBIL SET BILLREFFLG = 0 WHERE INVTYPE = 'CB' AND CAST(INVNO AS NVARCHAR(100)) IN (SELECT REFNO FROM BILLBYBILL WHERE TYPECODE = @SRETORDNO AND STYPE = 'SalesReturn' AND METHOD = 'Adjustment' AND VRTYPE = 'Cus.Opening' AND REFNO <> '')

		DELETE FROM BILLBYBILL WHERE TYPECODE = @SRETNO AND STYPE = 'SalesReturn' AND GENTYPE IN ('SR', 'SRB')
		DELETE FROM BATCHDET WHERE VRNO = @SRETNO AND STYPE = 'SR'

		DELETE FROM SNTSTK WHERE INVRTYPE = 'SR' AND INVRNO = @SRETNO AND INORDNO = @SRETORDNO
		DELETE FROM SNTSTKPHY WHERE INVRTYPE = 'SR' AND INVRNO = @SRETNO AND INORDNO = @SRETORDNO		

		--## Save LOGNOTE
		INSERT INTO [dbo].[LOGNOTE] (VRTYPE, VRNO, EDATE, USERCODE, NOTES, CFLAG, VSVRTYPE)
		SELECT 'SR' AS VRTYPE, @SRETNO AS VRNO, GETDATE() AS EDATE, @USERID AS USERCODE, 'Cancel' AS NOTES, 0 AS CFLAG, 0 AS VSVRTYPE

		SET @RESULT = 'Cancelled'

	END

	SELECT @RESULT AS MESSAGE, (CASE WHEN @RESULT = 'Cancelled' THEN 1 ELSE 0 END) AS STATUS

	COMMIT TRAN
	END TRY
	BEGIN CATCH	
		IF(@@TRANCOUNT > 0)
			ROLLBACK TRAN;
	SELECT 'Error: ' + ERROR_MESSAGE() AS MESSAGE, 0 AS STATUS
	END CATCH
END
