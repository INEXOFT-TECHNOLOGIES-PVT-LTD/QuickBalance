CREATE PROCEDURE [dbo].[ASK_SP_CancelSalesOrderDetails]
	@SORDNO INT,
	@USERID INT
AS
BEGIN	
	SET NOCOUNT ON;
	BEGIN TRY
	BEGIN TRAN

	DECLARE @RESULT NVARCHAR(MAX) = ''

	IF EXISTS (SELECT * FROM STKDT  WHERE ORDNO = @SORDNO AND TYPE = 'I' AND IIF(PRV IS NULL, 'N', PRV) <> 'Y' AND ((VRTYPE='NT' AND IIF(PRVN IS NULL,'N',PRVN)<>'Y') OR (VRTYPE='TR' AND IIF(PRVN IS NULL,'N',PRVN)<>'Y')))
		SET @RESULT = 'Invoice has been generated against this order.'
	IF EXISTS (SELECT * FROM CORDM WHERE STYPE = 'O' AND ORDNO = @SORDNO AND CANCELFLG = 1)
		SET @RESULT = 'The voucher has already been cancelled.'
	ELSE
	BEGIN

		--## Cancel Sales Order Details
		UPDATE CORDM SET DISCP = 0, DISCVAL = 0, NTVALUE = 0, TVALUE = 0, TAX = 0, COINADJ = 0, AMOUNT = 0, FREIGHT = 0, ULOGCD = @USERID, CUSDUITY = 0, CURCONRATE = 0, CURCODE = 0, CANCELFLG = 1, CLOSEREMARKS = '' WHERE ORDNO = @SORDNO AND STYPE = 'O'
		UPDATE CORDT SET ORGRATE = RATE, ORGQTY = QTY, RATE = 0, QTY = 0, CANCELFLG = 1, CONVTYPE = -1, CONVFACT = 1, CONVQTY = 0, CONVRATE = 0 WHERE ORDNO = @SORDNO AND STYPE = 'O'
		UPDATE CORDD SET ORGAMT = AMOUNT, ORGTAXAMT = TAXAMT, AMOUNT = 0, TAXAMT = 0, CANCELFLG = 1 WHERE VRNO = @SORDNO AND VRTYPE  ='O'

		DELETE FROM STKDT  WHERE ORDNO = @SORDNO AND TYPE = 'I' AND VRTYPE = 'O'
		DELETE FROM STKDTPHY  WHERE ORDNO = @SORDNO AND TYPE = 'I' AND VRTYPE = 'O'

		--## Save LOGNOTE
		INSERT INTO [dbo].[LOGNOTE] (VRTYPE, VRNO, EDATE, USERCODE, NOTES, CFLAG, VSVRTYPE)
		SELECT 'CORD' AS VRTYPE, @SORDNO AS VRNO, GETDATE() AS EDATE, @USERID AS USERCODE, 'Cancel' AS NOTES, 0 AS CFLAG, 0 AS VSVRTYPE

		SET @RESULT = 'Cancelled'

	END

	SELECT @RESULT AS MESSAGE, (CASE WHEN @RESULT = 'Cancelled' THEN 1 ELSE 0 END) AS STATUS

	COMMIT TRAN
	END TRY
	BEGIN CATCH	
		IF(@@TRANCOUNT > 0)
			ROLLBACK TRAN;
	SELECT ERROR_MESSAGE() AS MESSAGE, 0 AS STATUS
	END CATCH
END
